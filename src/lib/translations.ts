export const enToPt: TranslationDictionary = Object.entries(ptToEn).reduce<TranslationDictionary>(
  (acc, [pt, en]) => {
    if (!acc[en]) {
      acc[en] = pt;
    }
    return acc;
  },
  {}
);

export type TranslationLanguage = 'pt' | 'en';

export const translateCopy = (value: string, language: TranslationLanguage) => {
  const normalized = value.replace(/\s+/g, ' ').trim();
  const dictionary = language === 'en' ? ptToEn : enToPt;

  return dictionary[normalized] ?? value;
};
